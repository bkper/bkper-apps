/**
 * Discovery decision trial for System One models.
 *
 *   bun eval/system-one/run.ts            Print the results from the recorded responses.
 *   bun eval/system-one/run.ts --write    Rewrite the generated section of RESULTS.md from them.
 *   bun eval/system-one/run.ts --check    Fail when RESULTS.md does not match them.
 *   bun eval/system-one/run.ts --live     Call the models, record the responses, then --write.
 *
 * Live runs are paid calls and need BKPER_AI_BASE_URL (such as https://ai-dev.bkper.app/v1) and
 * BKPER_AI_OAUTH_TOKEN (from `bkper auth token`). Cases are synthetic.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { CASES } from './cases.js';
import { isSystemOneResponse } from './contract.js';
import { buildRequest } from './request.js';
import { renderReport, scoreRecording, type ModelPricing, type RecordedCall, type Recording } from './score.js';

const MODELS = ['jev', 'clef'];
const RELEASE = '2026-11-07';
const MAX_LIVE_CALLS = 100;
const RECORDING_PATH = join(import.meta.dir, 'recordings.json');
const RESULTS_PATH = join(import.meta.dir, 'RESULTS.md');
const START_MARKER = '<!-- generated:start -->';
const END_MARKER = '<!-- generated:end -->';

function isRecord(value: unknown): value is Record<string, unknown> {
    return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function isPricing(value: unknown): value is ModelPricing {
    return isRecord(value) && typeof value.inputNanoUsdPerToken === 'number' && typeof value.outputNanoUsdPerToken === 'number';
}

function isRecordedCall(value: unknown): value is RecordedCall {
    return isRecord(value)
        && typeof value.caseId === 'string'
        && typeof value.model === 'string'
        && typeof value.status === 'number'
        && typeof value.latencyMs === 'number'
        && isRecord(value.request)
        && 'body' in value;
}

function isRecording(value: unknown): value is Recording {
    return isRecord(value)
        && typeof value.recordedAt === 'string'
        && typeof value.endpoint === 'string'
        && typeof value.release === 'string'
        && isRecord(value.pricing)
        && Object.values(value.pricing).every(isPricing)
        && Array.isArray(value.calls)
        && value.calls.every(isRecordedCall);
}

async function readRecording(): Promise<Recording> {
    const value: unknown = JSON.parse(await readFile(RECORDING_PATH, 'utf8'));
    if (!isRecording(value)) throw new Error('recordings.json does not match the recording shape.');
    return value;
}

function generatedSection(recording: Recording): string {
    const header = `Generated by \`bun eval/system-one/run.ts --write\` from \`recordings.json\` (recorded ${recording.recordedAt} against \`${recording.endpoint}\`, Open System One ${recording.release}). Do not edit by hand.`;
    return `${START_MARKER}\n${header}\n\n${renderReport(scoreRecording(CASES, recording))}\n${END_MARKER}`;
}

function replaceGenerated(results: string, section: string): string {
    const start = results.indexOf(START_MARKER);
    const end = results.indexOf(END_MARKER);
    if (start < 0 || end < start) throw new Error('RESULTS.md has no generated section markers.');
    return `${results.slice(0, start)}${section}${results.slice(end + END_MARKER.length)}`;
}

async function fetchPricing(baseUrl: string): Promise<Record<string, ModelPricing>> {
    const response = await fetch(`${baseUrl}/models`);
    const catalog: unknown = await response.json();
    const pricing: Record<string, ModelPricing> = {};
    if (isRecord(catalog) && Array.isArray(catalog.data)) {
        for (const model of catalog.data) {
            if (isRecord(model) && typeof model.id === 'string' && MODELS.includes(model.id) && isPricing(model.pricing)) {
                pricing[model.id] = { inputNanoUsdPerToken: model.pricing.inputNanoUsdPerToken, outputNanoUsdPerToken: model.pricing.outputNanoUsdPerToken };
            }
        }
    }
    for (const model of MODELS) {
        if (!pricing[model]) throw new Error(`The model catalog has no pricing for ${model}.`);
    }
    return pricing;
}

async function record(): Promise<Recording> {
    const baseUrl = process.env.BKPER_AI_BASE_URL?.replace(/\/$/u, '');
    const token = process.env.BKPER_AI_OAUTH_TOKEN;
    if (!baseUrl || !token) throw new Error('Live runs need BKPER_AI_BASE_URL and BKPER_AI_OAUTH_TOKEN.');
    if (CASES.length * MODELS.length > MAX_LIVE_CALLS) throw new Error(`A live run is limited to ${MAX_LIVE_CALLS} calls.`);

    const endpoint = `${baseUrl}/systemone`;
    const pricing = await fetchPricing(baseUrl);
    const calls: RecordedCall[] = [];
    for (const discoveryCase of CASES) {
        for (const model of MODELS) {
            const request = buildRequest(model, discoveryCase);
            const started = performance.now();
            const response = await fetch(endpoint, {
                method: 'POST',
                headers: { 'Authorization': `Bearer ${token}`, 'Content-Type': 'application/json' },
                body: JSON.stringify(request),
            });
            const text = await response.text();
            const latencyMs = Math.round(performance.now() - started);
            let body: unknown = text;
            try {
                body = JSON.parse(text);
            } catch {
                // Keep a non-JSON body as text; scoring reports it as an invalid response.
            }
            calls.push({ caseId: discoveryCase.id, model, status: response.status, latencyMs, request, body });
            console.log(`${discoveryCase.id} ${model} ${response.status} ${latencyMs}ms${isSystemOneResponse(body) ? '' : ' (no answers)'}`);
        }
    }
    return { recordedAt: new Date().toISOString().slice(0, 10), endpoint: `${new URL(endpoint).origin}/v1/systemone`, release: RELEASE, pricing, calls };
}

const args = new Set(process.argv.slice(2));
if (args.has('--live')) {
    const recording = await record();
    await writeFile(RECORDING_PATH, `${JSON.stringify(recording, null, 2)}\n`);
    args.add('--write');
}

const section = generatedSection(await readRecording());
if (args.has('--write')) {
    await writeFile(RESULTS_PATH, replaceGenerated(await readFile(RESULTS_PATH, 'utf8'), section));
} else if (args.has('--check')) {
    const results = await readFile(RESULTS_PATH, 'utf8');
    if (replaceGenerated(results, section) !== results) throw new Error('RESULTS.md does not match recordings.json; run with --write.');
    console.log('RESULTS.md matches recordings.json.');
} else {
    console.log(section);
}
