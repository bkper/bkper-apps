/**
 * File classification trial: Gemini Decision through Open System One against Extractor Bot's current
 * Flash-Lite classification, on synthetic statements and single-transaction documents.
 *
 *   bun eval/classification/run.ts            Print the results from the recorded responses.
 *   bun eval/classification/run.ts --write    Rewrite the generated section of RESULTS.md from them.
 *   bun eval/classification/run.ts --check    Fail when RESULTS.md does not match them.
 *   bun eval/classification/run.ts --live     Call both models, record the responses, then --write.
 *
 * Live runs are paid calls and need BKPER_AI_BASE_URL (such as https://ai.bkper.app/v1) and
 * BKPER_AI_OAUTH_TOKEN (from `bkper auth token`). Documents are synthetic.
 */
import { access, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { isRecord } from '../../src/genai/BkperAIClientError.js';
import { CASES } from './cases.js';
import { callFlashLite, parseJson, type Exchange } from './flash-lite.js';
import { buildDecisionRequest, loadDocuments, redactDocument, type DocumentContent } from './request.js';
import { DECISION, FLASH_LITE, MODELS, renderReport, scoreRecording, type ModelPricing, type RecordedCall, type Recording } from './score.js';

const RELEASE = '2026-11-12';
const MAX_LIVE_CALLS = 100;
const RECORDING_PATH = join(import.meta.dir, 'recordings.json');
const RESULTS_PATH = join(import.meta.dir, 'RESULTS.md');
const START_MARKER = '<!-- generated:start -->';
const END_MARKER = '<!-- generated:end -->';

function isPricing(value: unknown): value is ModelPricing {
    return isRecord(value)
        && typeof value.inputNanoUsdPerToken === 'number'
        && typeof value.outputNanoUsdPerToken === 'number'
        && (value.cachedInputNanoUsdPerToken === undefined || typeof value.cachedInputNanoUsdPerToken === 'number');
}

function isRecordedCall(value: unknown): value is RecordedCall {
    return isRecord(value)
        && typeof value.caseId === 'string'
        && typeof value.model === 'string'
        && typeof value.status === 'number'
        && typeof value.latencyMs === 'number'
        && 'request' in value
        && 'body' in value;
}

function isRecording(value: unknown): value is Recording {
    return isRecord(value)
        && isRecord(value.recordedAt)
        && Object.values(value.recordedAt).every(date => typeof date === 'string')
        && isRecord(value.endpoints)
        && Object.values(value.endpoints).every(endpoint => typeof endpoint === 'string')
        && typeof value.release === 'string'
        && isRecord(value.pricing)
        && Object.values(value.pricing).every(isPricing)
        && Array.isArray(value.calls)
        && value.calls.every(isRecordedCall);
}

async function readRecording(): Promise<Recording | undefined> {
    try {
        await access(RECORDING_PATH);
    } catch {
        return undefined;
    }
    const value: unknown = JSON.parse(await readFile(RECORDING_PATH, 'utf8'));
    if (!isRecording(value)) throw new Error('recordings.json does not match the recording shape.');
    return value;
}

async function generatedSection(recording: Recording | undefined): Promise<string> {
    if (!recording) {
        return `${START_MARKER}\nNot recorded yet: run \`bun eval/classification/run.ts --live\`.\n${END_MARKER}`;
    }
    const sources = MODELS
        .map(model => `\`${model}\` recorded ${recording.recordedAt[model]} at \`${recording.endpoints[model]}\``)
        .join('; ');
    const header = `Generated by \`bun eval/classification/run.ts --write\` from \`recordings.json\` (${sources}; Open System One ${recording.release}). Do not edit by hand.`;
    const results = scoreRecording(CASES, await loadDocuments(CASES), recording);
    return `${START_MARKER}\n${header}\n\n${renderReport(results)}\n${END_MARKER}`;
}

function replaceGenerated(results: string, section: string): string {
    const start = results.indexOf(START_MARKER);
    const end = results.indexOf(END_MARKER);
    if (start < 0 || end < start) throw new Error('RESULTS.md has no generated section markers.');
    return `${results.slice(0, start)}${section}${results.slice(end + END_MARKER.length)}`;
}

async function fetchPricing(baseUrl: string): Promise<Record<string, ModelPricing>> {
    const response = await fetch(`${baseUrl}/models`);
    const catalog: unknown = await response.json();
    const pricing: Record<string, ModelPricing> = {};
    if (isRecord(catalog) && Array.isArray(catalog.data)) {
        for (const model of catalog.data) {
            if (isRecord(model) && typeof model.id === 'string' && MODELS.includes(model.id) && isPricing(model.pricing)) {
                const { inputNanoUsdPerToken, outputNanoUsdPerToken, cachedInputNanoUsdPerToken } = model.pricing;
                pricing[model.id] = {
                    inputNanoUsdPerToken,
                    outputNanoUsdPerToken,
                    ...(cachedInputNanoUsdPerToken !== undefined ? { cachedInputNanoUsdPerToken } : {}),
                };
            }
        }
    }
    for (const model of MODELS) {
        if (!pricing[model]) throw new Error(`The model catalog has no pricing for ${model}.`);
    }
    return pricing;
}

async function callDecision(endpoint: string, token: string, document: DocumentContent): Promise<Exchange> {
    const request = buildDecisionRequest(document);
    const started = performance.now();
    const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Authorization': `Bearer ${token}`, 'Content-Type': 'application/json', 'bkper-ai-source': 'extractor-bot-eval' },
        body: JSON.stringify(request),
    });
    const body = parseJson(await response.text());
    return { status: response.status, latencyMs: Math.round(performance.now() - started), request: redactDocument(request, document), body };
}

async function record(): Promise<Recording> {
    const baseUrl = process.env.BKPER_AI_BASE_URL?.replace(/\/$/u, '');
    const token = process.env.BKPER_AI_OAUTH_TOKEN;
    if (!baseUrl || !token) throw new Error('Live runs need BKPER_AI_BASE_URL and BKPER_AI_OAUTH_TOKEN.');

    let callCount = 0;
    const countCall = () => {
        callCount++;
        if (callCount > MAX_LIVE_CALLS) throw new Error(`A live run is limited to ${MAX_LIVE_CALLS} calls.`);
    };
    const pricing = await fetchPricing(baseUrl);
    const documents = await loadDocuments(CASES);
    const calls: RecordedCall[] = [];
    for (const classificationCase of CASES) {
        const document = documents.get(classificationCase.id);
        if (!document) throw new Error(`No document for ${classificationCase.id}.`);

        for (const exchange of await callFlashLite(baseUrl, token, document, countCall)) {
            calls.push({ caseId: classificationCase.id, model: FLASH_LITE, ...exchange });
            console.log(`${classificationCase.id} ${FLASH_LITE} ${exchange.status} ${exchange.latencyMs}ms`);
        }
        countCall();
        const exchange = await callDecision(`${baseUrl}/systemone`, token, document);
        calls.push({ caseId: classificationCase.id, model: DECISION, ...exchange });
        console.log(`${classificationCase.id} ${DECISION} ${exchange.status} ${exchange.latencyMs}ms`);
    }
    const origin = new URL(baseUrl).origin;
    const today = new Date().toISOString().slice(0, 10);
    return {
        recordedAt: { [FLASH_LITE]: today, [DECISION]: today },
        endpoints: { [FLASH_LITE]: `${origin}/v1/responses`, [DECISION]: `${origin}/v1/systemone` },
        release: RELEASE,
        pricing,
        calls,
    };
}

const args = new Set(process.argv.slice(2));
if (args.has('--live')) {
    await writeFile(RECORDING_PATH, `${JSON.stringify(await record(), null, 2)}\n`);
    args.add('--write');
}

const section = await generatedSection(await readRecording());
if (args.has('--write')) {
    await writeFile(RESULTS_PATH, replaceGenerated(await readFile(RESULTS_PATH, 'utf8'), section));
} else if (args.has('--check')) {
    const results = await readFile(RESULTS_PATH, 'utf8');
    if (replaceGenerated(results, section) !== results) throw new Error('RESULTS.md does not match recordings.json; run with --write.');
    console.log('RESULTS.md matches recordings.json.');
} else {
    console.log(section);
}
