/**
 * Invoice and receipt extraction trial: Clairic through Open System One against Extractor Bot's
 * current Gemini extraction.
 *
 *   bun eval/system-one/run.ts            Print the results from the recorded responses.
 *   bun eval/system-one/run.ts --write    Rewrite the generated section of RESULTS.md from them.
 *   bun eval/system-one/run.ts --check    Fail when RESULTS.md does not match them.
 *   bun eval/system-one/run.ts --live     Call the models, record the responses, then --write.
 *
 * Live runs are paid calls and need BKPER_AI_BASE_URL (such as https://ai-dev.bkper.app/v1) and
 * BKPER_AI_OAUTH_TOKEN (from `bkper auth token`). Documents are synthetic.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { CASES } from './cases.js';
import { isRecord, isSystemOneResponse } from './contract.js';
import { callGemini } from './gemini.js';
import { buildClairicRequest, loadDocuments } from './request.js';
import { CLAIRIC, GEMINI, renderReport, scoreRecording, type ModelPricing, type RecordedCall, type Recording } from './score.js';

const MODELS = [CLAIRIC, GEMINI];
const RELEASE = '2026-11-07';
const MAX_LIVE_CALLS = 90;
const RECORDING_PATH = join(import.meta.dir, 'recordings.json');
const RESULTS_PATH = join(import.meta.dir, 'RESULTS.md');
const START_MARKER = '<!-- generated:start -->';
const END_MARKER = '<!-- generated:end -->';

function isPricing(value: unknown): value is ModelPricing {
    return isRecord(value)
        && typeof value.inputNanoUsdPerToken === 'number'
        && typeof value.outputNanoUsdPerToken === 'number'
        && (value.cachedInputNanoUsdPerToken === undefined || typeof value.cachedInputNanoUsdPerToken === 'number');
}

function isRecordedCall(value: unknown): value is RecordedCall {
    return isRecord(value)
        && typeof value.caseId === 'string'
        && typeof value.model === 'string'
        && typeof value.status === 'number'
        && typeof value.latencyMs === 'number'
        && 'request' in value
        && 'body' in value;
}

function isRecording(value: unknown): value is Recording {
    return isRecord(value)
        && typeof value.recordedAt === 'string'
        && isRecord(value.endpoints)
        && Object.values(value.endpoints).every(endpoint => typeof endpoint === 'string')
        && typeof value.release === 'string'
        && isRecord(value.pricing)
        && Object.values(value.pricing).every(isPricing)
        && Array.isArray(value.calls)
        && value.calls.every(isRecordedCall);
}

async function readRecording(): Promise<Recording> {
    const value: unknown = JSON.parse(await readFile(RECORDING_PATH, 'utf8'));
    if (!isRecording(value)) throw new Error('recordings.json does not match the recording shape.');
    return value;
}

async function generatedSection(recording: Recording): Promise<string> {
    const endpoints = Object.entries(recording.endpoints).map(([model, endpoint]) => `\`${model}\` at \`${endpoint}\``).join(', ');
    const header = `Generated by \`bun eval/system-one/run.ts --write\` from \`recordings.json\` (recorded ${recording.recordedAt}; ${endpoints}; Open System One ${recording.release}). Do not edit by hand.`;
    const scores = scoreRecording(CASES, await loadDocuments(CASES), recording);
    return `${START_MARKER}\n${header}\n\n${renderReport(scores)}\n${END_MARKER}`;
}

function replaceGenerated(results: string, section: string): string {
    const start = results.indexOf(START_MARKER);
    const end = results.indexOf(END_MARKER);
    if (start < 0 || end < start) throw new Error('RESULTS.md has no generated section markers.');
    return `${results.slice(0, start)}${section}${results.slice(end + END_MARKER.length)}`;
}

async function fetchPricing(baseUrl: string): Promise<Record<string, ModelPricing>> {
    const response = await fetch(`${baseUrl}/models`);
    const catalog: unknown = await response.json();
    const pricing: Record<string, ModelPricing> = {};
    if (isRecord(catalog) && Array.isArray(catalog.data)) {
        for (const model of catalog.data) {
            if (isRecord(model) && typeof model.id === 'string' && MODELS.includes(model.id) && isPricing(model.pricing)) {
                const { inputNanoUsdPerToken, outputNanoUsdPerToken, cachedInputNanoUsdPerToken } = model.pricing;
                pricing[model.id] = {
                    inputNanoUsdPerToken,
                    outputNanoUsdPerToken,
                    ...(cachedInputNanoUsdPerToken !== undefined ? { cachedInputNanoUsdPerToken } : {}),
                };
            }
        }
    }
    for (const model of MODELS) {
        if (!pricing[model]) throw new Error(`The model catalog has no pricing for ${model}.`);
    }
    return pricing;
}

function parseBody(text: string): unknown {
    try {
        return JSON.parse(text);
    } catch {
        return text;
    }
}

async function record(): Promise<Recording> {
    const baseUrl = process.env.BKPER_AI_BASE_URL?.replace(/\/$/u, '');
    const token = process.env.BKPER_AI_OAUTH_TOKEN;
    if (!baseUrl || !token) throw new Error('Live runs need BKPER_AI_BASE_URL and BKPER_AI_OAUTH_TOKEN.');

    let callCount = 0;
    const countCall = () => {
        callCount++;
        if (callCount > MAX_LIVE_CALLS) throw new Error(`A live run is limited to ${MAX_LIVE_CALLS} calls.`);
    };
    const systemOneEndpoint = `${baseUrl}/systemone`;
    const pricing = await fetchPricing(baseUrl);
    const documents = await loadDocuments(CASES);
    const calls: RecordedCall[] = [];
    for (const extractionCase of CASES) {
        const document = documents.get(extractionCase.id);
        if (!document) throw new Error(`No document for ${extractionCase.id}.`);

        const request = buildClairicRequest(CLAIRIC, extractionCase, document);
        countCall();
        const started = performance.now();
        const response = await fetch(systemOneEndpoint, {
            method: 'POST',
            headers: { 'Authorization': `Bearer ${token}`, 'Content-Type': 'application/json', 'bkper-ai-source': 'parser-bot-eval' },
            body: JSON.stringify(request),
        });
        const body = parseBody(await response.text());
        const latencyMs = Math.round(performance.now() - started);
        calls.push({ caseId: extractionCase.id, model: CLAIRIC, status: response.status, latencyMs, request, body });
        console.log(`${extractionCase.id} ${CLAIRIC} ${response.status} ${latencyMs}ms${isSystemOneResponse(body) ? '' : ' (no answers)'}`);

        const exchanges = await callGemini(baseUrl, token, document, countCall);
        for (const exchange of exchanges) {
            calls.push({ caseId: extractionCase.id, model: GEMINI, ...exchange });
            console.log(`${extractionCase.id} ${GEMINI} ${exchange.status} ${exchange.latencyMs}ms`);
        }
    }
    const origin = new URL(baseUrl).origin;
    return {
        recordedAt: new Date().toISOString().slice(0, 10),
        endpoints: { [CLAIRIC]: `${origin}/v1/systemone`, [GEMINI]: `${origin}/v1/responses` },
        release: RELEASE,
        pricing,
        calls,
    };
}

const args = new Set(process.argv.slice(2));
if (args.has('--live')) {
    const recording = await record();
    await writeFile(RECORDING_PATH, `${JSON.stringify(recording, null, 2)}\n`);
    args.add('--write');
}

const section = await generatedSection(await readRecording());
if (args.has('--write')) {
    await writeFile(RESULTS_PATH, replaceGenerated(await readFile(RESULTS_PATH, 'utf8'), section));
} else if (args.has('--check')) {
    const results = await readFile(RESULTS_PATH, 'utf8');
    if (replaceGenerated(results, section) !== results) throw new Error('RESULTS.md does not match recordings.json; run with --write.');
    console.log('RESULTS.md matches recordings.json.');
} else {
    console.log(section);
}
