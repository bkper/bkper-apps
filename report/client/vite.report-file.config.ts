/**
 * Builds the report file bundle: the report renderer (`src/report-file/index.ts`) alone, with
 * the Web Awesome theme and `@bkper/web-design` tokens, into ONE script and ONE stylesheet with
 * nothing to load, written as a module the Worker imports (`server/src/generated/`). The Worker
 * inlines both into every report file it serves (`format: "html"`), so it never bundles per
 * request. Run with `npm run build:report-file`.
 */
import { defineConfig, type Plugin } from 'vite';

const OUT_DIR = '../server/src/generated';
const MODULE = 'report-file-bundle.ts';

export default defineConfig({
    publicDir: false,
    // Library builds keep `process.env.NODE_ENV` for their consumers; this bundle is final.
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
        outDir: OUT_DIR,
        emptyOutDir: true,
        cssCodeSplit: false,
        // Anything a stylesheet refers to becomes a data URL: the file may load nothing.
        assetsInlineLimit: () => true,
        lib: {
            entry: 'src/report-file/index.ts',
            formats: ['iife'],
            name: 'ReportFile',
            fileName: () => 'report-file.js',
        },
    },
    plugins: [reportFileModule()],
});

/** Replaces the build output with one TypeScript module exporting the script and the stylesheet. */
function reportFileModule(): Plugin {
    return {
        name: 'report-file-module',
        apply: 'build',
        enforce: 'post',
        generateBundle(_options, bundle) {
            const files = Object.values(bundle);
            const scripts = files.flatMap(file => (file.type === 'chunk' ? [file.code] : []));
            const styles = files.flatMap(file =>
                file.type === 'asset' && file.fileName.endsWith('.css') ? [String(file.source)] : []
            );
            const others = files.filter(
                file => file.type === 'asset' && !file.fileName.endsWith('.css')
            );
            if (scripts.length !== 1 || styles.length !== 1 || others.length > 0) {
                this.error(
                    `Expected one script and one stylesheet, got: ${files.map(file => file.fileName).join(', ')}`
                );
            }
            const script = scripts[0];
            const style = styles[0];
            // Inlined as they are, they must not end their element early. Without `<script`, an
            // HTML comment opener (as Lit templates have) cannot hide the closing `</script>`.
            const early = /<\/?script/i.exec(script) ?? /<\/style/i.exec(style);
            if (early) {
                const around = early.input.slice(Math.max(0, early.index - 80), early.index + 80);
                this.error(`The bundle has text that would end its inline element: ${around}`);
            }
            for (const name of Object.keys(bundle)) {
                delete bundle[name];
            }
            this.emitFile({
                type: 'asset',
                fileName: MODULE,
                source: [
                    '// Generated by `npm run build:report-file` (client/vite.report-file.config.ts). Do not edit.',
                    '',
                    '/** The report renderer, as one classic script to inline in a report file. */',
                    `export const REPORT_FILE_SCRIPT: string = ${JSON.stringify(script)};`,
                    '',
                    '/** Web Awesome, Bkper design tokens and the page, as one stylesheet to inline. */',
                    `export const REPORT_FILE_STYLE: string = ${JSON.stringify(style)};`,
                    '',
                ].join('\n'),
            });
        },
    };
}
